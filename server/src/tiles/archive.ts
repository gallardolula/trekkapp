/** Reads a vector tile archive produced by Planetiler.
 *
 *  An MBTiles file is a SQLite database, so it is read with the runtime's
 *  own SQLite rather than a dependency. Archives are opened once and kept
 *  open: a hike downloads thousands of tiles and reopening the file per
 *  request would dominate the cost of serving one.
 */
import { existsSync, statSync } from 'node:fs';
import { join } from 'node:path';

import { STYLE_REVISION } from './style';
import { DatabaseSync } from 'node:sqlite';

export interface RegionDefinition {
  id: string;
  name: string;
  description: string;
  bounds: { west: number; south: number; east: number; north: number };
  minZoom: number;
  maxZoom: number;
}

export interface RegionStatus extends RegionDefinition {
  available: boolean;
  sizeBytes: number;
  tileCount: number;
  /** Whether the region also has contour lines beside its basemap. */
  contours: boolean;
  /** Changes whenever the archive is regenerated, so a device can tell. */
  version: string;
}

/**
 * The contours of a region live in their own archive beside the basemap.
 *
 * Separate because they come from different data under different terms,
 * are generated by a different tool, and are regenerated on their own: the
 * basemap follows OpenStreetMap edits and the terrain does not change.
 */
export const contourId = (regionId: string) => `${regionId}-contours`;

/** Open archives, with the file signature each handle was opened on. */
const open = new Map<string, { handle: DatabaseSync; signature: string }>();

function archivePath(directory: string, id: string): string {
  return join(directory, `${id}.mbtiles`);
}

/**
 * The open handle for an archive, reopening it when the file has changed.
 *
 * Holding a handle for the lifetime of the process is what makes serving a
 * tile cheap, but a handle keeps the file it was opened on even after that
 * file is replaced. Regenerating an archive while the server runs then
 * leaves it serving the previous one from a deleted inode, with the
 * version it reports from the new file on disk: the phone is told the map
 * is current and handed the old one.
 *
 * The file's size and modification time are enough to notice. Both come
 * from a stat that `describe` was making anyway.
 */
function database(directory: string, id: string): DatabaseSync | null {
  const path = archivePath(directory, id);
  if (!existsSync(path)) {
    open.get(id)?.handle.close();
    open.delete(id);
    return null;
  }

  const stat = statSync(path);
  const signature = `${stat.mtimeMs}-${stat.size}`;
  const cached = open.get(id);
  if (cached) {
    if (cached.signature === signature) return cached.handle;
    cached.handle.close();
  }

  const handle = new DatabaseSync(path, { readOnly: true });
  open.set(id, { handle, signature });
  return handle;
}

export function closeArchives(): void {
  for (const entry of open.values()) entry.handle.close();
  open.clear();
}

export function describe(directory: string, region: RegionDefinition): RegionStatus {
  const path = archivePath(directory, region.id);
  if (!existsSync(path)) {
    return {
      ...region,
      available: false,
      sizeBytes: 0,
      tileCount: 0,
      contours: false,
      version: 'none',
    };
  }

  const stat = statSync(path);
  const db = database(directory, region.id)!;
  const row = db.prepare('SELECT count(*) AS n FROM tiles').get() as { n: number };

  // The contours are part of what a phone downloads for this region, so
  // they count towards its size and towards its version. A region whose
  // contours were regenerated is a region the phone has to fetch again.
  const contourPath = archivePath(directory, contourId(region.id));
  const contourStat = existsSync(contourPath) ? statSync(contourPath) : null;

  return {
    ...region,
    available: true,
    sizeBytes: stat.size + (contourStat?.size ?? 0),
    tileCount: Number(row.n),
    contours: contourStat !== null,
    // Derived from the files themselves, so regenerating an archive changes
    // it without anyone having to remember to bump a number, and from the
    // style revision, because the pack holds whatever the style asked for.
    version: [
      `${stat.mtimeMs.toFixed(0)}-${stat.size}`,
      contourStat ? `c${contourStat.mtimeMs.toFixed(0)}-${contourStat.size}` : 'c0',
      `s${STYLE_REVISION}`,
    ].join('-'),
  };
}

/**
 * Returns one tile, or null when the archive or the tile is absent.
 *
 * MBTiles addresses rows by the TMS scheme, whose vertical axis runs the
 * other way round from the one every map client uses. The conversion
 * happens here so nothing above this file has to know.
 */
export function readTile(
  directory: string,
  id: string,
  z: number,
  x: number,
  y: number,
): Uint8Array | null {
  const db = database(directory, id);
  if (!db) return null;

  const flippedY = 2 ** z - 1 - y;
  const row = db
    .prepare('SELECT tile_data FROM tiles WHERE zoom_level = ? AND tile_column = ? AND tile_row = ?')
    .get(z, x, flippedY) as { tile_data: Uint8Array } | undefined;

  return row?.tile_data ?? null;
}
